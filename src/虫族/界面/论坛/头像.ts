/**
 * 文字头像。
 *
 * 论坛里有几十个昵称，但没有图片素材——而且也不该有：外部图片要么挂在 CDN 上
 * 随时可能挂，要么内联成 base64 把代码块撑爆。
 *
 * 做法：昵称首字 + 一个由昵称算出来的稳定色相。同一个人永远同一个颜色，
 * 不同的人大概率不同色。配上 CSS 的径向高光与描边，远看就是个头像。
 * 这个手法参考了 `酒馆数据/角色卡/寻找伪男` 那张卡的小手机群聊。
 */

/**
 * 头像底色板。全部取中低饱和度的色，跟暖纸底放在一起不会打架。
 * 避免纯红——那是「已赞」「未读」这些状态色的专属。
 */
const 色板 = [
  { 字: '#6b7f9e', 底: '#e6ebf2' }, // 灰蓝
  { 字: '#8a7a5c', 底: '#f0ead9' }, // 卡其
  { 字: '#7a8f72', 底: '#e8efe3' }, // 苔绿
  { 字: '#96707a', 底: '#f2e6ea' }, // 藕粉
  { 字: '#6f8b8a', 底: '#e3eeed' }, // 青灰
  { 字: '#9a7f5e', 底: '#f4ebdc' }, // 蜜棕
  { 字: '#7d7396', 底: '#eae7f2' }, // 紫灰
  { 字: '#8a6f6f', 底: '#f1e6e4' }, // 陶土
];

/** 「我」固定用朱砂，一眼认出自己 */
export const 我的头像色 = { 字: '#ffffff', 底: '#b8422c' };

/** 楼主固定用金色 */
export const 楼主头像色 = { 字: '#ffffff', 底: '#b8893f' };

/**
 * 昵称 → 稳定索引。同一个昵称永远同一个值。
 *
 * 用一个简单的字符串散列（djb2 变体）。不需要密码学强度，
 * 只要分布均匀、且在同一份数据里稳定即可。
 */
function 散列(值: string): number {
  let h = 5381;
  for (let i = 0; i < 值.length; i++) {
    h = ((h << 5) + h + 值.charCodeAt(i)) >>> 0;
  }
  return h;
}

/**
 * 取一个昵称的头像配色。
 *
 * @param 昵称 用户昵称
 * @param 我的 是不是「我」——是的话固定朱砂色
 * @param 楼主 是不是本帖楼主——是的话固定金色
 */
export function 头像色(昵称: string, 我的 = false, 楼主 = false): { 字: string; 底: string } {
  if (我的) return 我的头像色;
  if (楼主) return 楼主头像色;
  const 名 = (昵称 ?? '').trim() || '匿名';
  return 色板[散列(名) % 色板.length];
}

/** 头像上显示的字：中文取首字，英文取首字母大写 */
export function 头像字(昵称: string): string {
  const 名 = (昵称 ?? '').trim();
  if (!名) return '?';
  // 去掉前缀的「匿名」之类装饰，让首字更有辨识度
  const 净 = 名.replace(/^匿名/, '');
  const 用 = 净 || 名;
  const 首 = 用[0];
  return /[a-z]/i.test(首) ? 首.toUpperCase() : 首;
}
