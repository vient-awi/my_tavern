function dlcEnemyData(params: {
  level: number;
  sexPower: number;
  charm: number;
  luck: number;
  evasion: number;
  crit: number;
  endurance: number;
  maxPleasure: number;
  baseEndurance?: number;
}): EnemyBaseData {
  return {
    对手等级: params.level,
    对手魅力: params.charm,
    对手幸运: params.luck,
    对手闪避率: params.evasion,
    对手暴击率: params.crit,
    对手耐力: params.endurance,
    对手最大耐力: params.endurance,
    对手快感: 0,
    对手最大快感: params.maxPleasure,
    对手高潮次数: 0,
    对手性斗力: params.sexPower,
    对手忍耐力: params.baseEndurance ?? params.level * 10,
  };
}

